// Builds src/data/us-outline.js: one simplified outline of the contiguous U.S. (no state lines),
// in the same 975×610 Albers USA frame as the landfill map. Used as a faint hero texture, so it is
// precomputed instead of shipping the full us-atlas data with the first screen.
// Run: node scripts/build_us_outline.mjs
import { writeFileSync, readFileSync } from 'node:fs';
import { geoAlbersUsa, geoPath } from 'd3-geo';
import { merge } from 'topojson-client';

const us = JSON.parse(readFileSync(new URL('../node_modules/us-atlas/states-10m.json', import.meta.url)));
const OFF_MAP = new Set(['02', '15', '72', '78', '60', '66', '69']); // AK, HI and territories
const lower48 = us.objects.states.geometries.filter((g) => !OFF_MAP.has(g.id));
const projection = geoAlbersUsa().scale(1300).translate([975 / 2, 610 / 2]);
const raw = geoPath(projection)(merge(us, lower48));

// Round to whole units and drop points that land on the previous one (≈1 px at hero size)
const out = [];
for (const ring of raw.split('M').filter(Boolean)) {
  const pts = ring.replace(/Z/g, '').split('L').map((p) => p.split(',').map((v) => Math.round(Number(v))));
  const kept = pts.filter((p, i) => i === 0 || Math.abs(p[0] - pts[i - 1][0]) + Math.abs(p[1] - pts[i - 1][1]) >= 2);
  if (kept.length < 4) continue; // tiny islands
  out.push('M' + kept.map((p) => p.join(',')).join('L') + 'Z');
}
const d = out.join('');
writeFileSync(
  new URL('../src/data/us-outline.js', import.meta.url),
  `// Generated by scripts/build_us_outline.mjs. Do not edit by hand.\nexport const US_OUTLINE = '${d}';\n`
);
console.log('rings', out.length, 'chars', d.length);
