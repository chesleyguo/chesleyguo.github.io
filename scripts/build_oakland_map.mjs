// Builds src/data/oakland/oakland-map.js for the Oakland camera map on the research card.
// Inputs (both public, committed next to the output):
//   src/data/oakland/oakland_boundary.geojson  Oakland city limits, U.S. Census Bureau 2023
//                                              cartographic boundary file (cb_2023_06_place_500k)
//   src/data/oakland/cameras.csv               the 18 camera sites, OakDOT ArcGIS layer
// Only locations are used: no speeds, counts or results.
// Run: node scripts/build_oakland_map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { geoMercator, geoPath } from 'd3-geo';

const dir = new URL('../src/data/oakland/', import.meta.url);
const boundary = JSON.parse(readFileSync(new URL('oakland_boundary.geojson', dir)));
const lines = readFileSync(new URL('cameras.csv', dir), 'utf8').split(/\r?\n/).filter((l) => l && !l.startsWith('#'));
const header = lines[0].split(',');
const parseLine = (l) => (l.match(/("([^"]|"")*"|[^,]*)(,|$)/g) || []).map((c) => c.replace(/,$/, '').replace(/^"|"$/g, '').replace(/""/g, '"'));
const cams = lines.slice(1).map((l) => Object.fromEntries(parseLine(l).slice(0, header.length).map((v, i) => [header[i], v])));
if (cams.length !== 18) throw new Error(`expected 18 cameras, got ${cams.length}`);

const W = 600;
const H = 520;
const projection = geoMercator().fitExtent([[16, 16], [W - 16, H - 16]], boundary);
const round = (d) => d.replace(/\d+\.\d+/g, (n) => (+n).toFixed(1));
const outline = round(geoPath(projection)(boundary));
const cameras = cams.map((c) => {
  const [x, y] = projection([Number(c.long), Number(c.lat)]);
  if (!Number.isFinite(x) || !Number.isFinite(y)) throw new Error(`camera ${c.location_number}: bad coordinates`);
  return { n: Number(c.location_number), street: c.main_street, cross: c.cross_streets, x: +x.toFixed(1), y: +y.toFixed(1) };
});

writeFileSync(
  new URL('oakland-map.js', dir),
  `// Generated by scripts/build_oakland_map.mjs. Do not edit by hand.\n` +
    `export const VIEW = { w: ${W}, h: ${H} };\n` +
    `export const OAKLAND_OUTLINE = '${outline}';\n` +
    `export const CAMERAS = ${JSON.stringify(cameras, null, 2)};\n`
);
console.log('outline chars', outline.length, 'cameras', cameras.length);
